const KEYS = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);
const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const RE = new RegExp(`(?<![\\w₂])(${KEYS.map(esc).join("|")})(?![\\w₂])`, "g");

export function Abbr({ term, children }: { term: string; children?: ReactNode }) {
  const t = GLOSSARY[term];
  if (!t) return <>{children ?? term}</>;
  return (
    <span className="group/abbr relative inline cursor-help underline decoration-slate-500/60 decoration-dotted underline-offset-2" tabIndex={0}>
      {children ?? term}
      <span role="tooltip" className="pointer-events-none invisible absolute bottom-full left-0 z-50 mb-1 w-64 rounded-lg border border-slate-200 dark:border-white/10 bg-white dark:bg-slate-950/95 p-2 text-[11px] font-normal normal-case leading-snug tracking-normal text-slate-700 dark:text-slate-300 opacity-0 shadow-xl transition group-hover/abbr:visible group-hover/abbr:opacity-100 group-focus/abbr:visible group-focus/abbr:opacity-100">
        <b className="block text-slate-900 dark:text-slate-100">{term} — {t.full}</b>{t.def}
      </span>
    </span>
  );
}

/** Wrap every glossary term found in a plain string with a hover definition. Non-strings pass through. */
export function glossify(node: ReactNode): ReactNode {
  if (typeof node !== "string") return node;
  const parts = node.split(RE);
  if (parts.length === 1) return node;
  return parts.map((p, i) => (i % 2 ? <Abbr key={i} term={p} /> : <Fragment key={i}>{p}</Fragment>));
}
